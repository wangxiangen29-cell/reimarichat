// 从人设规则里提取【台词范例】的 few-shot 台词（去掉「」括号），供每个角色独立示例用
// 标题可能是「【台词范例（摘自《东方香霖堂》原文…）】」这类带括号注释的形式，不能按闭合的【台词范例】精确匹配
function extractPersonaFewShots(text) {
  const s = String(text || '');
  const startMarker = '【台词范例';
  const idx = s.indexOf(startMarker);
  if (idx === -1) return [];
  const headEnd = s.indexOf('】', idx + startMarker.length);
  if (headEnd === -1) return [];
  const contentBegin = headEnd + 1;
  const endIdx = s.indexOf('【互动示范', contentBegin);
  const section = endIdx === -1 ? s.slice(contentBegin) : s.slice(contentBegin, endIdx);
  return (section.match(/「([^」]*)」/g) || [])
    .map((q) => q.replace(/[「」]/g, '').trim())
    .filter(Boolean)
    .slice(0, 4);
}

