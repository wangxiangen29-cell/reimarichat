// 从人设规则里提取【台词范例】的 few-shot 台词（去掉「」括号），供每个角色独立示例用
function extractPersonaFewShots(text) {
  const s = String(text || '');
  const idx = s.indexOf('【台词范例】');
  const end = s.indexOf('【互动示范】');
  const section = idx === -1 ? '' : s.slice(idx + '【台词范例】'.length, end === -1 ? s.length : end);
  return (section.match(/「([^」]*)」/g) || [])
    .map((q) => q.replace(/[「」]/g, '').trim())
    .filter(Boolean)
    .slice(0, 4);
}

